import { Hono } from "hono";

import { currentUser, requireRole } from "../lib/auth.js";
import { badRequest, conflict, notFound } from "../lib/errors.js";
import { getProgramOrThrow } from "../lib/programs.js";
import { clone, getNextId, readDb, writeDb } from "../store.js";

export const values = new Hono();

const ATTRIBUTE_KEYS = ["TERM_MONTHS", "APR_RATE", "CASH_AMOUNT"] as const;

function toValuesResponse(db: Awaited<ReturnType<typeof readDb>>, revision: Awaited<ReturnType<typeof readDb>>["revisions"][number]) {
  const scopeVehicles = revision.vehicles.flatMap((selection) => {
    const vehicle = db.vehicles.find(
      (item) => item.vehicleCatalogId === selection.vehicleCatalogId,
    );
    if (!vehicle) return [];
    const trim = vehicle.trimName ? ` ${vehicle.trimName}` : "";
    return [{
      revisionVehicleId: selection.revisionVehicleId,
      vehicleCatalogId: selection.vehicleCatalogId,
      label: `${vehicle.year} ${vehicle.make} ${vehicle.model}${trim}`,
    }];
  });

  return {
    financeTerms: revision.setup.financeTerms,
    scopeVehicles,
    components: revision.values.components,
  };
}

/**
 * GET /api/programs/:programId/revisions/:revisionId/values
 */
values.get("/programs/:programId/revisions/:revisionId/values", async (c) => {
  currentUser(c);
  const programId = Number(c.req.param("programId"));
  const revisionId = Number(c.req.param("revisionId"));

  if (!Number.isInteger(programId) || programId <= 0 || !Number.isInteger(revisionId) || revisionId <= 0) {
    throw badRequest("VALIDATION_ERROR", "programId and revisionId must be positive integers");
  }

  const db = await readDb();
  const program = getProgramOrThrow(db, programId);
  const revision = db.revisions.find(
    (item) => item.id === revisionId && item.programId === program.id,
  );

  if (!revision) {
    throw notFound("REVISION_NOT_FOUND", "Revision not found");
  }

  return c.json(toValuesResponse(db, revision));
});

/**
 * PUT /api/programs/:programId/revisions/:revisionId/values
 *
 * Replaces the component/attribute collection. Internal identifiers are
 * generated by the mock service; clients send only stable business keys.
 */
values.put("/programs/:programId/revisions/:revisionId/values", async (c) => {
  const user = requireRole(c, "AUTHOR", "ADMIN");
  const programId = Number(c.req.param("programId"));
  const revisionId = Number(c.req.param("revisionId"));

  if (!Number.isInteger(programId) || programId <= 0 || !Number.isInteger(revisionId) || revisionId <= 0) {
    throw badRequest("VALIDATION_ERROR", "programId and revisionId must be positive integers");
  }

  const body = await c.req.json().catch(() => null);
  if (!body || typeof body !== "object" || Array.isArray(body)) {
    throw badRequest("VALIDATION_ERROR", "Request body must be an object");
  }

  const db = await readDb();
  const program = getProgramOrThrow(db, programId);
  const revision = db.revisions.find(
    (item) => item.id === revisionId && item.programId === program.id,
  );

  if (!revision) {
    throw notFound("REVISION_NOT_FOUND", "Revision not found");
  }
  if (revision.status !== "DRAFT") {
    throw conflict("REVISION_NOT_EDITABLE", "Values can only be edited while the revision is DRAFT");
  }

  const input = body as Record<string, unknown>;
  if (!Array.isArray(input.components)) {
    throw badRequest("VALIDATION_ERROR", "components must be an array");
  }

  let nextComponentId = Math.max(0, ...revision.values.components.map((item) => item.componentId)) + 1;
  let nextAttributeId = Math.max(
    0,
    ...revision.values.components.flatMap((component) =>
      component.attributes.map((attribute) => attribute.attributeId),
    ),
  ) + 1;

  const nextComponents = input.components.map((value, index) => {
    if (!value || typeof value !== "object" || Array.isArray(value)) {
      throw badRequest("VALIDATION_ERROR", `components[${index}] must be an object`);
    }

    const componentInput = value as Record<string, unknown>;
    const componentCode = typeof componentInput.componentCode === "string" ? componentInput.componentCode.trim() : "";
    const componentName = typeof componentInput.componentName === "string" ? componentInput.componentName.trim() : "";
    if (!componentCode || !componentName || !Array.isArray(componentInput.attributes) || componentInput.attributes.length === 0) {
      throw badRequest("VALIDATION_ERROR", `components[${index}] requires componentCode, componentName and at least one attribute`);
    }

    const existing = revision.values.components.find((item) => item.componentCode === componentCode);
    const componentId = existing?.componentId ?? nextComponentId++;
    const attributes = componentInput.attributes.map((attributeValue, attributeIndex) => {
      if (!attributeValue || typeof attributeValue !== "object" || Array.isArray(attributeValue)) {
        throw badRequest("VALIDATION_ERROR", `components[${index}].attributes[${attributeIndex}] must be an object`);
      }

      const attribute = attributeValue as Record<string, unknown>;
      if (typeof attribute.key !== "string" || !ATTRIBUTE_KEYS.includes(attribute.key as (typeof ATTRIBUTE_KEYS)[number])) {
        throw badRequest("VALIDATION_ERROR", `components[${index}].attributes[${attributeIndex}].key is invalid`);
      }
      if (attribute.numberValue !== undefined && attribute.numberValue !== null && typeof attribute.numberValue !== "number") {
        throw badRequest("VALIDATION_ERROR", "numberValue must be a number or null");
      }
      if (attribute.textValue !== undefined && attribute.textValue !== null && typeof attribute.textValue !== "string") {
        throw badRequest("VALIDATION_ERROR", "textValue must be a string or null");
      }

      const previous = existing?.attributes.find((item) => item.key === attribute.key);
      return {
        attributeId: previous?.attributeId ?? nextAttributeId++,
        key: attribute.key as (typeof ATTRIBUTE_KEYS)[number],
        numberValue: typeof attribute.numberValue === "number" ? attribute.numberValue : null,
        textValue: typeof attribute.textValue === "string" ? attribute.textValue : null,
      };
    });

    const sequenceNo = typeof componentInput.sequenceNo === "number" && Number.isInteger(componentInput.sequenceNo)
      ? componentInput.sequenceNo
      : index + 1;

    return {
      componentId,
      componentCode,
      componentName,
      sequenceNo,
      attributes,
      vehicleOverrides: existing?.vehicleOverrides ?? [],
    };
  });

  revision.values = {
    ...revision.values,
    components: clone(nextComponents),
  };

  if (!revision.isMinorRevision) {
    revision.approval.isSubmitted = false;
    revision.approval.submittedAt = null;
    revision.approval.submittedBy = null;
    revision.approval.approved = false;
    revision.approval.approvedAt = null;
    revision.approval.approvedBy = null;
    revision.approval.approvalComment = null;
    revision.approval.rejectedAt = null;
    revision.approval.rejectedBy = null;
    revision.approval.rejectionReason = null;
  }

  const now = new Date().toISOString();
  program.updatedAt = now;
  db.activity.unshift({
    id: getNextId(db.activity),
    entityType: "INCENTIVE_REVISION",
    entityId: revision.id,
    operation: "UPDATE",
    changedBy: user.username,
    changedAt: now,
    programId: program.id,
    programName: program.name,
    programIdentifier: program.identifier,
  });

  await writeDb(db);
  return c.json(toValuesResponse(db, revision));
});
